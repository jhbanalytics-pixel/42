CREATE OR REPLACE VIEW `{project}.{dataset}.v_source_lab_v2` AS
WITH ranked_sources AS (
  SELECT
    contract_version,
    run_id,
    client_scope_id,
    market_scope,
    brand_config_id,
    audience_lens_ids,
    theme_id,
    source_performance_id,
    metric_date,
    vendor,
    http_method,
    route_path,
    endpoint_id,
    route_role,
    source_family,
    market,
    status,
    platform,
    resource,
    catalog_digest,
    official_credits,
    official_credits_label,
    official_archetype,
    catalog_paginated,
    catalog_metered,
    cache_ttl_seconds,
    delivery,
    docs_url,
    calls,
    credits,
    `rows`,
    integrity,
    geo_precision,
    unique_lift,
    last_success_at,
    downstream_consumers,
    official_capability,
    official_parameters,
    official_price_components,
    blocking_reason,
    kill_test_result,
    review_date,
    last_checked_at,
    balance,
    observed_at,
    balance_read_status,
    recent_deductions,
    deductions_interval,
    funding_math_status,
    funded_increase_amount,
    funded_increase_observed,
    selected_top_up_credits,
    baseline_credits_per_day,
    baseline_window,
    runway_days,
    monthly_optional_credit_cap,
    monthly_optional_credits_used,
    optional_calls_enabled,
    ROW_NUMBER() OVER (
      PARTITION BY
        client_scope_id,
        vendor,
        http_method,
        route_path,
        COALESCE(market, 'global')
      ORDER BY metric_date DESC, last_checked_at DESC, run_id DESC
    ) AS source_rank
  FROM `{project}.{dataset}.source_performance_daily_v2`
  WHERE client_scope_id != 'qa_canary'
)
SELECT
  contract_version,
  run_id,
  client_scope_id,
  market_scope,
  brand_config_id,
  audience_lens_ids,
  theme_id,
  source_performance_id,
  metric_date,
  vendor,
  http_method,
  route_path,
  endpoint_id,
  route_role,
  source_family,
  market,
  status,
  platform,
  resource,
  catalog_digest,
  official_credits,
  official_credits_label,
  official_archetype,
  catalog_paginated,
  catalog_metered,
  cache_ttl_seconds,
  delivery,
  docs_url,
  calls,
  credits,
  `rows`,
  integrity,
  geo_precision,
  unique_lift,
  last_success_at,
  downstream_consumers,
  official_capability,
  official_parameters,
  official_price_components,
  blocking_reason,
  kill_test_result,
  review_date,
  last_checked_at,
  balance,
  observed_at,
  balance_read_status,
  recent_deductions,
  deductions_interval,
  funding_math_status,
  funded_increase_amount,
  funded_increase_observed,
  selected_top_up_credits,
  baseline_credits_per_day,
  baseline_window,
  runway_days,
  monthly_optional_credit_cap,
  monthly_optional_credits_used,
  optional_calls_enabled
FROM ranked_sources
WHERE source_rank = 1;
